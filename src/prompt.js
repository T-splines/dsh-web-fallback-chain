/**
 * The one system-prompt section this plugin contributes.
 *
 * ## Why this exists
 *
 * `dsh-tool-web` already injects a paragraph per tool, but both paragraphs are
 * about **trust and citation**: "results are external, untrusted data" and "cite
 * the URL". Neither says *when to reach for the tool*, and nothing in the static
 * tool description does either. The observed failure mode is not calling the tool
 * wrongly — it is not calling it at all on questions whose answer lives in
 * documentation or someone else's repository, because the local checkout is
 * right there and looks like the authoritative source.
 *
 * That is a routing problem, so it belongs in a prompt section rather than in a
 * tool description: the tool description is generated by `dsh-tool-web` and is
 * not ours to change, while `ctx.systemPrompt.section()` is a supported seam that
 * composes additively with the shipped sections.
 *
 * ## Why it is worded as a discriminator
 *
 * "Use the web more" is not actionable and does not survive contact with a
 * tempting local source. The section instead draws one falsifiable line — 用法
 * (how does this API/framework/library work) versus 调试 (why does my own code
 * fail) — because that is the distinction whose absence caused the miss. A rule
 * with a checkable criterion is worth more than an exhortation.
 *
 * ## Placement
 *
 * Sits between the fetch section and LSP: after both shipped web sections, so it
 * reads as a qualification of them rather than a competing preamble. Registered
 * under the plugin's own name so a composition can shadow it.
 *
 * @module dsh-web-fallback-chain/prompt
 */

/** Stable section name; a composition can shadow or replace it by this name. */
export const PROMPT_SECTION = 'tool:web_routing'

/**
 * Fallback order used when the system-prompt service does not publish
 * `TOOL_WEB_FETCH`. Mirrors `SECTION_ORDERS.TOOL_WEB_FETCH` (2100) so the section
 * lands in the same place on a deployment that names its orders differently.
 */
const FALLBACK_ORDER = 2100

/** The section text. Kept as one string so it can be asserted in tests. */
export const PROMPT_TEXT = [
  'Search the web before reading local source when the question is how something is *meant* to be used.',
  '',
  '- **Usage questions** — "how do I write X with framework/API Y", "what is the recommended way", "is there an existing implementation of Z" — start with `web_search`, then `web_fetch` the best source. The answer lives in docs or someone else\'s repository, not in the checkout you happen to have open. Prefer official documentation, then real source on GitHub, then community write-ups.',
  '- **Debugging questions** — "why does *my* code fail", "why is this config not taking effect" — start from the local evidence (logs, the code you just wrote, the resolved config). That is first-hand data no search can replace.',
  '- When both apply, search first to establish what correct looks like, then read locally to find where this case departs from it.',
  '- After two failed attempts at the same problem, stop editing and go look for a working implementation instead of producing a third variation.',
].join('\n')

/**
 * Register the routing section.
 *
 * ## Why `ctx.get()` and not `ctx.systemPrompt`
 *
 * Cordis's context proxy throws `cannot get property "X" without inject` for any
 * property that is not a declared dependency — and it throws at *property read*,
 * so a guard like `if (ctx.systemPrompt === undefined)` never gets a chance to be
 * false; the read itself is the failure. Because `applyPromptSection` runs inside
 * `apply()`, that throw takes the whole plugin down with it: neither chain
 * registers, and the seam reports the far less actionable
 * `configured web provider "fetch-chain" is not registered`.
 *
 * `ctx.get(name)` is the documented way to read a service **without** the inject
 * requirement: it returns `undefined` for an absent service instead of throwing.
 * That keeps `systemPrompt` and `tools` optional collaborators without listing
 * them in `inject` — listing them would turn their absence into a hard dependency
 * that blocks the providers, which is the worse trade.
 *
 * Late-bound on purpose: the section text is a thunk, so it is re-read whenever
 * the prompt is assembled and the section disappears if the tool it talks about
 * is not registered in this scope.
 *
 * @param ctx - context whose `systemPrompt` service receives the section.
 */
export function applyPromptSection(ctx) {
  // `ctx.get` is a mixin method present on every context; the optional call keeps
  // a bare test double (a plain object) usable here.
  const softGet = (serviceName) => (typeof ctx?.get === 'function' ? ctx.get(serviceName) : undefined)
  const prompt = softGet('systemPrompt')
  // Optional service: a deployment may compose without a prompt builder (a bare
  // test host, for instance). Missing here is not an error worth failing over.
  if (prompt === undefined || prompt === null || typeof prompt.section !== 'function') return
  const tools = softGet('tools')

  const order = typeof prompt.getSectionOrder === 'function'
    ? prompt.getSectionOrder('TOOL_WEB_FETCH')
    : undefined

  prompt.section({
    name: PROMPT_SECTION,
    order: Number.isFinite(order) ? order + 1 : FALLBACK_ORDER,
    text: ({ scope }) => {
      if (tools === undefined || tools === null || typeof tools.get !== 'function') return PROMPT_TEXT
      // Only speak when there is something to speak about.
      return tools.get('web_search', scope) === undefined ? '' : PROMPT_TEXT
    },
  })
}
